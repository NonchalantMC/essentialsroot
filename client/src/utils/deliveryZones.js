// Reverse lookup built once at module load: area name -> { fee, eta, label }.
const AREA_INDEX = {};
for (const [, region] of Object.entries(DELIVERY_ZONES)) {
  const areaEntries = Object.entries(region.areas);
  const isSingleAreaRegion = areaEntries.length === 1;
  for (const [areaKey, area] of areaEntries) {
    AREA_INDEX[areaKey] = {
      fee: area.fee,
      eta: area.eta,
      label: isSingleAreaRegion
        ? region.label
        : `${region.label} — ${areaKey.replace(/\b\w/g, c => c.toUpperCase())}`,
    };
  }
}

export function getDeliveryFee(cityInput, subtotal) {
  if (!cityInput || cityInput.trim().length < 2) {
    return { fee: 0, label: "Waiting for area...", eta: "—", isEstimated: true, isValid: false };
  }

  const match = AREA_INDEX[cityInput.toLowerCase().trim()];

  if (!match) {
    return { fee: 0, label: "Please select a valid town", eta: "—", isEstimated: true, isValid: false };
  }

  return { fee: match.fee, label: match.label, eta: match.eta, isEstimated: false, isValid: true };
}